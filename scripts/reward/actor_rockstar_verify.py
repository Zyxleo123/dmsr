def plan_path(run: Path, arm: str) -> Path:
    return run / f"actor_plan_{arm}.json"


def results_path(run: Path, arm: str) -> Path:
    return run / f"actor_verification_{arm}.jsonl"


def probe_stage_dir(run: Path, arm: str) -> Path:
    return run / f"probe_{arm}"


def actor_field_path(run: Path, arm: str, box: str) -> Path:
    return probe_stage_dir(run, arm) / "actor_fields" / f"{box}.npy"


def _require_probe_checkpoint(run: Path, arm: str) -> Path:
    """The probe EMA checkpoint, verified to actually BE a probe.

    An unstamped checkpoint here would mean the tiles being verified were made
    by something other than the capped, offline-gated probe the criterion is
    about -- most likely a production run smuggled in by path.
    """
    ck = probe_stage_dir(run, arm) / "ema_generator.pt"
    if not ck.is_file():
        raise SystemExit(
            f"no probe checkpoint at {ck}; produced by "
            f"scripts/reward/train_sr2_direct.py --arm {arm} --probe")
    blob = torch.load(str(ck), map_location="cpu", weights_only=False)
    extra = dict(blob.get("extra") or {})
    if not bool(extra.get("probe_only")):
        raise SystemExit(
            f"{ck} is not stamped probe_only; the actor gate only means "
            "something when its tiles come from the capped probe run")
    if str(extra.get("arm", arm)) != str(arm):
        raise SystemExit(
            f"{ck} was trained for arm {extra.get('arm')!r}, not {arm!r}")
    del blob
    return ck


def _require_field_gates(run: Path, arm: str, agate: Mapping) -> None:
    """The probe must not have broken the field before its splices count.

    A probe that wrecked the density power spectrum can still move the proxy's
    features in ways Rockstar responds to; passing THAT sign check would
    validate nothing an actual actor run could use.
    """
    if not bool(agate.get("require_probe_field_gates", True)):
        return
    g = run / f"gate_probe_{arm}.json"
    if not g.is_file():
        raise SystemExit(
            f"actor_gate.require_probe_field_gates is set and {g} is missing; "
            f"produced by scripts/reward/score_sr2_direct.py with "
            f"--tag probe_{arm} (score the probe checkpoint's fields first)")
    doc = json.loads(g.read_text())
    if not bool(doc.get("passed", False)):
        raise SystemExit(
            f"the probe checkpoint failed the field gates ({g}); its splices "
            "would measure a broken field, not the proxy. Not selecting.")


