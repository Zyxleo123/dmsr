#!/usr/bin/env python
"""The actor-like Rockstar gate: verify the proxy on tiles the actor MADE.

``splice_verify.py`` re-runs the halo finder on tiles drawn from the labelled
candidate pool -- HR, frozen seeds, interventions. Every one of those is a field
the proxy's training distribution has seen the likes of. The actor is not: a
fine-tuned generator moves through a family of fields nothing in the pool
represents, and a proxy can rank the whole pool correctly while being wrong
about precisely those. So the gate that authorizes fine-tuning is measured on
tiles GENERATED BY a probe_only fine-tuned checkpoint, spliced into held-out
frozen boxes, and re-run through the real Rockstar.

Two stages:

``select`` (GPU, minutes)
    Load the probe checkpoint (``train_sr2_direct.py --probe``), generate the
    held-out verify boxes with it, compute the arm's features against each
    box's frozen reference, and choose ``n_actor_checks`` tiles stratified the
    same way the splice plan is (``predicted_positive`` / ``high_uncertainty``
    / ``random``), spread over at least ``min_actor_boxes`` boxes. Writes the
    plan and the generated fields it needs.
``run`` (CPU, hours -- one array task per check)
    Splice one actor tile into its frozen box, run Rockstar on the complete
    periodic box, and append the measured ``dR`` next to the predicted one to
    ``actor_verification_<arm>.jsonl`` -- the file
    ``gate_catalog_proxy.actor_verification`` consumes. Missing results never
    count as a pass.

    python scripts/reward/actor_rockstar_verify.py --stage select --arm b
    python scripts/reward/actor_rockstar_verify.py --stage run --arm b --index 0
"""
