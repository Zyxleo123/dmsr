#!/usr/bin/env python
"""Full P(k) curves for a map2map checkpoint, candidate vs frozen SR2 vs HR.

``m2m_field_report.py`` reduces each spectrum to ONE number -- the mean of
``P_cand/P_HR`` over the top third of k bins (``_highk``, frac=1/3). For a 512^3
box that window is k ~ 170-256 cycles/box. Our LR input is 64^3 and so carries
nothing above k = 32, which means the scored window sits 5-8x ABOVE the LR
Nyquist: every bit of power there has to be generated by the network.

That reduction produced a result worth checking rather than believing:

    field          candidate    frozen SR2
    displacement    1.2e-04       0.403
    velocity        1.1e-05       0.960
    density         1.14          0.993

Density near 1 while displacement and velocity are ~1e-4 is not a contradiction
-- the Lagrangian-to-Eulerian map is strongly nonlinear, so displacing particles
by a SMOOTH large-scale field piles them into caustics and manufactures high-k
density. But that is an argument, not a measurement, and it predicts something
specific and checkable: the candidate's displacement/velocity spectra should
track HR at low k and fall off a cliff near the LR Nyquist (k ~ 32), while its
density spectrum tracks HR much further out.

This dumps the whole curve so that prediction can be looked at rather than
reasoned about, and so the figure can be redrawn without regenerating a box.
It deliberately does NOT reduce anything: no ``_highk``, no ratio averaging.
Two things the single number cannot show and this can:

* WHERE the candidate stops tracking HR -- at the LR Nyquist (smooth upsampling)
  or somewhere else (a real but band-limited generator).
* Whether ``_highk``'s mean-of-ratios is distorted by bins where ``P_HR`` is
  near zero. It clips the denominator at 1e-30 and weights every bin equally,
  so one near-empty HR bin can dominate. The curves show ``P_HR`` itself.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import numpy as np
import torch

PROJECT_ROOT = Path(__file__).resolve().parents[2]
for _p in (PROJECT_ROOT / "src", PROJECT_ROOT / "scripts" / "reward",
           PROJECT_ROOT / "scripts" / "features", PROJECT_ROOT / "scripts" / "sr2"):
    if str(_p) not in sys.path:
        sys.path.insert(0, str(_p))

from _common import banner  # noqa: E402
from _sr2_direct import geometry_of, load_direct_config, load_hr, load_lr  # noqa: E402
from overfit_host_mse import BOXSIZE, NG_HR  # noqa: E402
from m2m_field_report import load_m2m_generator  # noqa: E402

from cosmo_sr.eval.baseline_srs import super_resolve_srs  # noqa: E402
from cosmo_sr.eval.density import cic_density  # noqa: E402
from cosmo_sr.eval.spectra import power_spectrum  # noqa: E402
from cosmo_sr.reward.base import find_base_field  # noqa: E402

#: (label, channel). Integers, not slices -- the same convention
#: ``sr2_scratch_field_report.FIELDS`` uses, i.e. ONE component of each vector
#: field. For an isotropic field that is the same ratio as summing components,
#: and keeping the convention identical is what makes these curves comparable to
#: the numbers already reported.
FIELDS = (("displacement", 0), ("velocity", 3))


def curves(sr, frozen, hr, *, cell_kpc_h, dis_norm_kpc_h, device):
    """``{field: {k, pk_sr, pk_frozen, pk_hr}}`` -- raw spectra, no reduction."""
    out = {}
    for name, ch in FIELDS:
        k, pk_sr = power_spectrum(sr[ch])
        _, pk_fz = power_spectrum(frozen[ch])
        _, pk_hr = power_spectrum(hr[ch])
        out[name] = {"k": k, "pk_sr": pk_sr, "pk_frozen": pk_fz, "pk_hr": pk_hr}

    def dens(f):
        t = torch.as_tensor(np.ascontiguousarray(f[0:3]))[None].to(device)
        return cic_density(t, cell_kpc_h, dis_norm_kpc_h)[0, 0].cpu().numpy()

    k, pk_sr = power_spectrum(dens(sr))
    _, pk_fz = power_spectrum(dens(frozen))
    _, pk_hr = power_spectrum(dens(hr))
    out["density"] = {"k": k, "pk_sr": pk_sr, "pk_frozen": pk_fz, "pk_hr": pk_hr}
    return out


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--ckpt", required=True)
    ap.add_argument("--repo", required=True)
    ap.add_argument("--model", default="srsgan.G")
    ap.add_argument("--style-a", type=float, default=1.0)
    ap.add_argument("--style-size", type=int, default=1)
    ap.add_argument("--config", default="configs/reward/sr2_direct_finetune.yaml")
    ap.add_argument("--set", action="append", default=[], metavar="KEY=VALUE")
    ap.add_argument("--box", default="set9")
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--out", default="")
    ap.add_argument("--device", default="")
    a = ap.parse_args(argv)

    cfg = load_direct_config(a)
    geom = geometry_of(cfg)
    device = torch.device(a.device
                          or ("cuda" if torch.cuda.is_available() else "cpu"))

    frozen_path = find_base_field(a.box, seed=int(a.seed))
    if frozen_path is None:
        print(f"no cached frozen SR2 box for {a.box} seed {a.seed}; nothing to "
              "compare against. Build it with scripts/reward/cache_sr2_base.py.")
        return 0

    g, prov = load_m2m_generator(
        Path(a.ckpt), Path(a.repo), scale_factor=geom.scale_factor,
        in_chan=6, out_chan=6, style_size=a.style_size, style_a=a.style_a,
        model=a.model, device=device)
    banner(f"power curves: {Path(a.ckpt).name} (epoch {prov['epoch']}) on {a.box}")

    hr = np.ascontiguousarray(load_hr(cfg, a.box), dtype=np.float32)
    lr = np.asarray(load_lr(cfg, a.box), dtype=np.float32)
    sr = super_resolve_srs(g, lr, scale_factor=geom.scale_factor,
                           nsplit=geom.nsplit, pad=geom.pad,
                           seed=int(a.seed), device=device)
    frozen = np.asarray(np.load(str(frozen_path), mmap_mode="r"),
                        dtype=np.float32)

    cell = BOXSIZE * 1e3 / float(NG_HR)
    dis_norm = float(cfg.get("geometry", {}).get("dis_norm_kpc_h", 6000.0))
    cur = curves(sr, frozen, hr, cell_kpc_h=cell, dis_norm_kpc_h=dis_norm,
                 device=device)

    # The LR Nyquist, in the same units power_spectrum returns (cycles/box).
    # This is the number the falloff should be compared against: below it the
    # network can pass structure through, above it everything must be generated.
    lr_nyquist = lr.shape[1] // 2
    print(f"  LR is {lr.shape[1]}^3 -> LR Nyquist = k {lr_nyquist} cycles/box")
    print(f"  HR is {hr.shape[1]}^3 -> k runs to {hr.shape[1] // 2}")
    print()
    for name in ("displacement", "velocity", "density"):
        c = cur[name]
        k = c["k"]
        print(f"  {name}")
        for kk in (4, 8, 16, 32, 64, 128, 200):
            i = int(np.argmin(np.abs(k - kk)))
            r_sr = c["pk_sr"][i] / max(c["pk_hr"][i], 1e-30)
            r_fz = c["pk_frozen"][i] / max(c["pk_hr"][i], 1e-30)
            flag = "  <- LR Nyquist" if kk == lr_nyquist else ""
            print(f"     k={k[i]:7.1f}  P/P_HR cand {r_sr:10.3e}   "
                  f"frozen {r_fz:8.3f}   P_HR {c['pk_hr'][i]:.3e}{flag}")
        print()

    # THE DIAGNOSTIC NUMBER. "Does the cutoff move with training?" needs one
    # scalar per checkpoint, not three tables. k_half is the largest k at which
    # the candidate still holds half of HR's power -- i.e. where the field stops
    # tracking. If it climbs above the LR Nyquist epoch over epoch, the model is
    # learning to synthesise and the long run is justified; if it stays pinned
    # at the Nyquist, more epochs will not move it.
    print("  CUTOFF (largest k with P/P_HR >= 0.5):")
    for name in ("displacement", "velocity", "density"):
        c = cur[name]
        k, r = c["k"], c["pk_sr"] / np.clip(c["pk_hr"], 1e-30, None)
        ok = np.where(r >= 0.5)[0]
        kh = float(k[ok[-1]]) if ok.size else float("nan")
        print(f"     {name:13s} k_half = {kh:7.1f}   "
              f"({kh / lr_nyquist:.2f} x LR Nyquist)")
    print()

    out = Path(a.out) if a.out else Path(a.ckpt).parent / f"power_curves_{Path(a.ckpt).stem}_{a.box}"
    np.savez_compressed(
        str(out.with_suffix(".npz")),
        lr_nyquist=lr_nyquist, box=a.box, ckpt=str(a.ckpt),
        **{f"{n}_{q}": cur[n][q] for n in cur for q in cur[n]})
    print(f"wrote {out.with_suffix('.npz')}  (curves; replot without recomputing)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
